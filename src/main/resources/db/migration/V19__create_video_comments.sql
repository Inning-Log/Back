-- A comment belongs to one uploaded video, never to a merged video or an entire timeline.
create table video_comments (
    id bigint generated by default as identity primary key,
    video_id bigint not null references inning_record_videos(id),
    author_user_id bigint not null references app_users(id),
    client_comment_id varchar(36) not null,
    request_fingerprint varchar(64) not null,
    content varchar(1000) not null check (char_length(trim(content)) > 0),
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone not null,
    deleted_at timestamp(6) with time zone,
    constraint uq_video_comment_client unique(video_id, author_user_id, client_comment_id)
);
create index idx_video_comments_page on video_comments(video_id, deleted_at, id);
create index idx_video_comments_author on video_comments(author_user_id, deleted_at);
