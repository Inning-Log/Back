-- One rendered inning segment, shared between game videos with the same contents.
-- render_key is a hash of everything drawn in the segment, so an unchanged inning is never rendered twice.
create table segment_renders (
    id bigint generated by default as identity primary key,
    render_key varchar(64) not null,
    object_key varchar(512) not null,
    status varchar(12) not null check (status in ('PROCESSING', 'READY', 'FAILED')),
    duration_seconds numeric(9, 3),
    failure_reason varchar(100),
    attempts integer not null default 1,
    requested_at timestamp(6) with time zone not null,
    completed_at timestamp(6) with time zone,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone not null,
    constraint uq_segment_renders_key unique (render_key)
);
create index idx_segment_renders_status on segment_renders(status, requested_at);

-- A merged, shareable game video requested by one user, optionally with friends' clips.
create table game_videos (
    id bigint generated by default as identity primary key,
    user_id bigint not null references app_users(id),
    game_id bigint not null references games(id),
    mode varchar(15) not null check (mode in ('SOLO', 'WITH_FRIENDS')),
    status varchar(10) not null check (status in ('RENDERING', 'MERGING', 'READY', 'FAILED')),
    object_key varchar(512) not null,
    segment_count integer not null check (segment_count > 0),
    duration_seconds numeric(9, 3),
    failure_reason varchar(100),
    requested_at timestamp(6) with time zone not null,
    merge_requested_at timestamp(6) with time zone,
    completed_at timestamp(6) with time zone,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone not null,
    deleted_at timestamp(6) with time zone,
    constraint uq_game_videos_object_key unique (object_key)
);
create index idx_game_videos_user_game on game_videos(user_id, game_id, deleted_at);
create index idx_game_videos_status on game_videos(status, deleted_at);

-- Participants in card order. Position 0 is the requester.
create table game_video_members (
    game_video_id bigint not null references game_videos(id),
    position integer not null check (position >= 0),
    user_id bigint not null references app_users(id),
    primary key (game_video_id, position),
    constraint uq_game_video_members_user unique (game_video_id, user_id)
);

-- Inning segments in playback order.
create table game_video_segments (
    game_video_id bigint not null references game_videos(id),
    position integer not null check (position >= 0),
    segment_render_id bigint not null references segment_renders(id),
    inning_number integer not null,
    half varchar(6) check (half in ('TOP', 'BOTTOM')),
    primary key (game_video_id, position)
);
create index idx_game_video_segments_render on game_video_segments(segment_render_id);
