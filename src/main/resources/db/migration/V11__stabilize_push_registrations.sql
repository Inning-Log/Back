-- noinspection SqlNoDataSourceInspection
alter table user_push_tokens
    drop constraint uk_user_push_tokens_user_device;

-- V10 allowed the same installation identifier under different users. Keep the
-- most recently active owner before enforcing installation-level ownership.
delete from user_push_tokens
where id in (
    select id
    from (
        select id,
               row_number() over (
                   partition by device_id
                   order by last_seen_at desc, enabled desc, id desc
               ) as duplicate_rank
        from user_push_tokens
    ) ranked_tokens
    where duplicate_rank > 1
);

alter table user_push_tokens
    add constraint uk_user_push_tokens_device unique (device_id);

create table push_registration_locks (
    id smallint primary key,
    name varchar(50) not null unique
);

insert into push_registration_locks (id, name)
