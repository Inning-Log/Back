-- One active video per inning record. The file itself lives in S3; this row tracks ownership and upload state.
create table inning_record_videos (
    id bigint generated by default as identity primary key,
    inning_record_id bigint not null references inning_records(id),
    object_key varchar(512) not null,
    content_type varchar(100) not null,
    size_bytes bigint not null check (size_bytes > 0),
    status varchar(10) not null check (status in ('PENDING', 'READY')),
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone not null,
    uploaded_at timestamp(6) with time zone,
    deleted_at timestamp(6) with time zone,
    constraint uq_inning_record_videos_object_key unique(object_key)
);
-- Only one active row per record is enforced in the service under the inning record row lock.
create index idx_inning_record_videos_record on inning_record_videos(inning_record_id, deleted_at);
